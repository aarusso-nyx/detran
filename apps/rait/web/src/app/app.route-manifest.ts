export interface RaitRouteEntry {
  /** Como na tabela, sem barra inicial; `''` para `/`. */
  readonly path: string;
  readonly kind: RaitRouteKind;
  /**
   * `T-nn` ou `null`. A forma `T-${string}`/`IU-RAIT-${string}` do contrato §2 é provada por
   * C-2A-02; o tipo fica `string` para que os predicados `screen is string`/`sheet is string`
   * dos specs do Inspector compilem (TS2677 — uma restrição de tipo mais estreita no parâmetro).
   */
  readonly screen: string | null;
  /** `IU-RAIT-nnn` ou `null` (idem). */
  readonly sheet: string | null;
  readonly module: RaitModule;
  /** `'all'` = `todos` (M4). */
  readonly roles: readonly RaitRoleCode[] | 'all';
  readonly resolver: string | null;
  /** `UC-RAIT-nnn` sem colchetes. */
  readonly uc: readonly string[];
  /** `JRN-RAIT-nnn` e `JW-nn` (`JW-01…12` expandido em 12 ids). */
  readonly journeys: readonly string[];
  /** M13 (adenda A3); `null` em `redirect`/`layout`. */
  readonly level: RaitRouteLevel | null;
}

