/** Regra da tabela A (puro): `/` → `-`, `:param` → `param`, `''` → `home`. */
export function screenSlugOf(path: string): string {
  return path === '' ? 'home' : path.replace(/:/g, '').replace(/\//g, '-');
}

const SCREENS_NAMESPACE = 'rait.screens';

/** `rait.screens.<slug>.title` — título de janela/breadcrumb da rota. */
export function titleKeyOf(entry: RaitRouteEntry): string {
  return `${SCREENS_NAMESPACE}.${screenSlugOf(entry.path)}.title`;
}

/** Entradas de um módulo, na ordem do manifesto. */
export function manifestEntriesOf(
  module: RaitModule,
): readonly RaitRouteEntry[] {
  return RAIT_ROUTE_MANIFEST.filter((entry) => entry.module === module);
}

/** Entrada pelo `path` exato do manifesto; lança quando ausente (nunca `undefined`). */
export function manifestEntryOf(path: string): RaitRouteEntry {
  const entry = RAIT_ROUTE_MANIFEST.find(
    (candidate) => candidate.path === path,
  );
  if (!entry) {
    throw new Error(`rota fora do manifesto: "${path}"`);
  }
  return entry;
}
