#!/usr/bin/env node
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const requireApp = createRequire(path.join(root, 'backend/app/package.json'));
const version = JSON.parse(
  fs.readFileSync(path.join(root, 'tools/stynx-version.json'), 'utf8'),
).version;
const check = process.argv.includes('--check');
if (process.argv.slice(2).some((arg) => arg !== '--check'))
  throw new Error('Only --check is supported');
if (version !== '1.6.1')
  throw new Error('D-161 storage generation requires exact STYNX 1.6.1');

const binding = {
  ownerRole: 'postgres',
  appRole: 'role_app_backend',
  readerRole: null,
  tenantTable: { schema: 'auth', table: 'tenants', column: 'id' },
};
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');
const packages = [
  ['@stynx-nyx/outbox', 'renderOutboxStorage', '19-stynx-outbox.sql'],
  ['@stynx-nyx/offline-sync', 'renderOfflineStorage', '19-stynx-offline.sql'],
];
const outputs = new Map();
const entries = [];
for (const [name, renderName, filename] of packages) {
  const entrypoint = requireApp.resolve(name);
  const artifact = requireApp(name)[renderName](binding);
  if (
    artifact.packageVersion !== version ||
    JSON.stringify(artifact.binding) !== JSON.stringify(binding)
  )
    throw new Error(`${name}: installed storage identity/binding mismatch`);
  const target = `backend/database/ddl/${filename}`;
  const sql = `-- Generated by tools/generate-stynx-storage.mjs from installed ${name}@${version}.\n-- D-161: fresh-target storage projection; existing receipts and history remain immutable.\n${artifact.objectsSql}\n${artifact.roleBindingsSql}`;
  outputs.set(target, sql);
  entries.push({
    package: name,
    packageVersion: artifact.packageVersion,
    contractVersion: artifact.contractVersion,
    entrypointSha256: digest(fs.readFileSync(entrypoint)),
    binding: artifact.binding,
    target,
    sha256: digest(sql),
    objectsSha256: digest(artifact.objectsSql),
    roleBindingsSha256: digest(artifact.roleBindingsSql),
    manifest: artifact.manifest,
  });
}
outputs.set(
  'backend/database/stynx-storage.json',
  await format(
    JSON.stringify({ version: 1, stynxVersion: version, artifacts: entries }),
    { filepath: path.join(root, 'backend/database/stynx-storage.json') },
  ),
);
for (const [target, bytes] of outputs) {
  const file = path.join(root, target);
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== bytes)
      throw new Error(`${target}: differs from installed published renderer`);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, bytes);
  }
}
console.log(
  `stynx-storage: ${check ? 'verified' : 'generated'} ${outputs.size} artifacts (${version})`,
);
